"""Turn finished runs into results/RESULTS.md plus figures."""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np

from .experiments import PAPER, PAPER_BASELINES

SPLIT_NAMES = {"random": "Interpolation (random)", "group": "Structural (unseen hosts)",
               "target": "Property (out-of-range target)", "target_group": "Coupled (hosts + target)",
               "temporal": "Temporal MP18 -> MP21", "nelements": "Unary/binary -> ternary/quaternary"}
C_POOL, C_TEST, C_REF = "#5b7fa6", "#d9822b", "#8a8f98"


def _plt():
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({"font.size": 9, "axes.spines.top": False, "axes.spines.right": False,
                         "figure.dpi": 150, "savefig.bbox": "tight"})
    return plt


def _panel(ax, yo, po, yt, pt, rng, title, unit):
    lo, hi = min(yo.min(), yt.min(), pt.min()), max(yo.max(), yt.max(), pt.max())
    pad = 0.04 * (hi - lo)
    ax.axvspan(rng[0], rng[1], color="#eef1f5", zorder=0, lw=0)          # training target range
    ax.plot([lo - pad, hi + pad], [lo - pad, hi + pad], color=C_REF, lw=0.8, ls="--", zorder=1)
    ax.scatter(yo, po, s=3, color=C_POOL, alpha=0.35, lw=0, label="out-of-fold (pool)", rasterized=True)
    ax.scatter(yt, pt, s=4, color=C_TEST, alpha=0.55, lw=0, label="test", rasterized=True)
    ax.set_xlim(lo - pad, hi + pad); ax.set_ylim(lo - pad, hi + pad); ax.set_aspect("equal")
    ax.set_title(title, fontsize=9, loc="left")
    ax.set_xlabel(f"DFT ({unit})"); ax.set_ylabel(f"predicted ({unit})")


def parity(yo, po, yt, pt, rng, path, title="", unit=""):
    plt = _plt()
    fig, ax = plt.subplots(figsize=(4, 4))
    _panel(ax, yo, po, yt, pt, rng, title, unit)
    ax.legend(frameon=False, loc="upper left", markerscale=3)
    fig.savefig(path); plt.close(fig)


def _load(runs: Path):
    out = {}
    for f in sorted(runs.glob("*.json")):
        d = json.loads(f.read_text())
        d["_npz"] = f.with_suffix(".npz")
        out[d["key"]] = d
    return out


def _f(x, nd=3):
    return "–" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:.{nd}f}"


def _grid(R, keys, titles, path, unit):
    plt = _plt()
    keys = [k for k in keys if k in R]
    if not keys:
        return False
    n = len(keys)
    cols = 2 if n == 4 else n
    fig, axes = plt.subplots(int(np.ceil(n / cols)), cols, figsize=(3.6 * cols, 3.6 * int(np.ceil(n / cols))),
                             squeeze=False)
    for ax, k, t in zip(axes.ravel(), keys, titles):
        z = np.load(R[k]["_npz"])
        _panel(ax, z["y_oof"], z["pred_oof"], z["y_test"], z["pred_test"], R[k]["train_range"],
               f"{t}\ntest RMSE {R[k]['test']['rmse']:.3f}", unit)
    axes.ravel()[0].legend(frameon=False, loc="upper left", markerscale=3, fontsize=8)
    for ax in axes.ravel()[n:]:
        ax.axis("off")
    fig.tight_layout(); fig.savefig(path); plt.close(fig)
    return True


def build(runs="results/runs", out="results"):
    runs, out = Path(runs), Path(out)
    (out / "figures").mkdir(parents=True, exist_ok=True)
    R = _load(runs)
    if not R:
        raise SystemExit(f"no runs under {runs}")
    L = ["# Results", "",
         "Generated by `python -m dgtl report`. Every number in the *this code* columns comes from the runs in "
         "`results/runs/`; *paper* columns are copied from Sugiura & Mizoguchi, PRX Intelligence 1, 023019 (2026). "
         "RMSE and MAE are in the target's unit (eV/atom for formation energy).", ""]

    # ---- LIC headline
    lic = ["random", "group", "target", "target_group"]
    if any(f"lic/eform/{s}/svr/all" in R for s in lic):
        L += ["## Layered intercalation compounds: four scenarios", "",
              "| Scenario | n test | SVR RMSE (this code) | SVR RMSE (paper) | Ridge RMSE (this code) | "
              "End-to-end CGCNN (paper) | SVR MAE | SVR R² |", "|---|---|---|---|---|---|---|---|"]
        for s in lic:
            a, b = R.get(f"lic/eform/{s}/svr/all"), R.get(f"lic/eform/{s}/ridge/all")
            p = PAPER.get(f"lic/eform/{s}/svr/all", {})
            e2e = PAPER_BASELINES.get(f"lic/eform/{s}", {}).get("End-to-end CGCNN")
            if not (a or b):
                continue
            L.append(f"| {SPLIT_NAMES[s]} | {(a or b)['n_test']} | {_f(a and a['test']['rmse'])} | {_f(p.get('rmse'))} | "
                     f"{_f(b and b['test']['rmse'])} | {_f(e2e)} | {_f(a and a['test']['mae'])} | {_f(a and a['test']['r2'])} |")
        if _grid(R, [f"lic/eform/{s}/svr/all" for s in lic], [SPLIT_NAMES[s] for s in lic],
                 out / "figures" / "lic_parity_svr.png", "eV/atom"):
            L += ["", "![LIC parity plots](figures/lic_parity_svr.png)", "",
                  "Grey band: the range of target values seen in training. Points outside it are property extrapolation."]
        L.append("")

    # ---- AoI headline
    rows = [("3 GNNs + SVR", "aoi/eform/temporal/svr/all"), ("3 GNNs + ridge", "aoi/eform/temporal/ridge/all"),
            ("Matminer + SVR", "aoi/eform/temporal/svr/matminer"), ("Matminer + ridge", "aoi/eform/temporal/ridge/matminer")]
    if any(k in R for _, k in rows):
        L += ["## Alloys, temporal split (train MP18, test MP21 additions)", "",
              "*Inside* / *outside* split the test set at the top of the training range (1.575 eV/atom).", "",
              "| Model | RMSE all | RMSE inside | RMSE outside | MAE | R² | paper: all / inside / outside |",
              "|---|---|---|---|---|---|---|"]
        for name, k in rows:
            if k not in R:
                continue
            d, p = R[k], PAPER.get(k, {})
            ref = f"{_f(p.get('rmse'))} / {_f(p.get('rmse_inside'))} / {_f(p.get('rmse_outside'))}" if p else "–"
            L.append(f"| {name} | {_f(d['test']['rmse'])} | {_f(d['test_inside'].get('rmse'))} | "
                     f"{_f(d['test_outside'].get('rmse'))} | {_f(d['test']['mae'])} | {_f(d['test']['r2'])} | {ref} |")
        for name, v in PAPER_BASELINES["aoi/eform/temporal"].items():
            L.append(f"| {name} (paper, not re-run) | {_f(v)} | – | – | – | – | – |")
        if _grid(R, [k for _, k in rows[:3]], [n for n, _ in rows[:3]], out / "figures" / "aoi_parity.png", "eV/atom"):
            L += ["", "![AoI parity plots](figures/aoi_parity.png)"]
        L.append("")

    # ---- how much extrapolation actually happens
    L += ["## How far do predictions leave the training range?", "",
          "RMSE alone hides whether a model extrapolates or just lands near the edge of what it saw. "
          "*Slope* is the least-squares slope of predicted against true value over the test rows whose true value "
          "lies outside the training range: 1.0 means the trend continues undamped, 0 means predictions are flat.", "",
          "| Experiment | test rows outside range | predictions outside range | slope outside | RMSE inside | RMSE outside |",
          "|---|---|---|---|---|---|"]
    for k, d in R.items():
        if d["frac_true_outside"] > 0.02 and d["features"] and k.endswith(("/all", "/matminer")):
            L.append(f"| `{k}` | {d['frac_true_outside']:.0%} | {d['frac_pred_outside']:.0%} | {_f(d['slope_outside'], 2)} | "
                     f"{_f(d['test_inside'].get('rmse'))} | {_f(d['test_outside'].get('rmse'))} |")
    L.append("")

    # ---- reliability diagnostics
    dg = [(k, d) for k, d in R.items() if d.get("diagnostic") and k.endswith("/all")]
    if dg:
        L += ["## Can unreliable predictions be flagged?", "",
              "Correlation between a label-free diagnostic score and the absolute test error. "
              "SVR: 1 − max RBF similarity to any training point. Ridge: max |x_j w_j|.", "",
              "| Experiment | Pearson | Spearman | mean score, inside | mean score, outside |", "|---|---|---|---|---|"]
        for k, d in dg:
            g = d["diagnostic"]
            L.append(f"| `{k}` | {_f(g['pearson'], 2)} | {_f(g['spearman'], 2)} | {_f(g['mean_score_inside'])} | "
                     f"{_f(g['mean_score_outside'])} |")
        L.append("")

    # ---- ablations
    feats = ["cgcnn", "schnet", "dimenetpp", "cgcnn+schnet", "cgcnn+dimenetpp", "schnet+dimenetpp", "all"]
    cols = [("lic", s) for s in lic] + [("aoi", "temporal")]
    if any(f"{ds}/eform/{s}/svr/{f}" in R for ds, s in cols for f in feats[:-1]):
        L += ["## Which GNN features matter? (SVR, test RMSE)", "",
              "| Features | " + " | ".join(f"{ds.upper()} {s}" for ds, s in cols) + " | AoI outside |",
              "|---|" + "---|" * (len(cols) + 1)]
        for f in feats:
            cells = [_f(R.get(f"{ds}/eform/{s}/svr/{f}", {}).get("test", {}).get("rmse")) for ds, s in cols]
            cells.append(_f(R.get(f"aoi/eform/temporal/svr/{f}", {}).get("test_outside", {}).get("rmse")))
            L.append(f"| {f} | " + " | ".join(cells) + " |")
        L.append("")
    regs = ["svr", "ridge", "svr_linear", "svr_poly", "local_ridge", "mlp"]
    if any(f"{ds}/eform/{s}/{r}/all" in R for ds, s in cols for r in regs[2:]):
        L += ["## Which regressor matters? (3 GNNs, test RMSE)", "",
              "| Regressor | " + " | ".join(f"{ds.upper()} {s}" for ds, s in cols) + " | AoI outside |",
              "|---|" + "---|" * (len(cols) + 1)]
        for r in regs:
            cells = [_f(R.get(f"{ds}/eform/{s}/{r}/all", {}).get("test", {}).get("rmse")) for ds, s in cols]
            cells.append(_f(R.get(f"aoi/eform/temporal/{r}/all", {}).get("test_outside", {}).get("rmse")))
            L.append(f"| {r} | " + " | ".join(cells) + " |")
        L.append("")
    other = [(k, d) for k, d in R.items() if "[" in k or "/nelements/" in k or "/efermi/" in k]
    if other:
        L += ["## Other extrapolation settings", "",
              "| Experiment | split | n pool / test | RMSE | RMSE outside | slope outside | R² | paper RMSE |",
              "|---|---|---|---|---|---|---|---|"]
        for k, d in other:
            L.append(f"| `{k}` | {d['split_description']} | {d['n_pool']} / {d['n_test']} | {_f(d['test']['rmse'])} | "
                     f"{_f(d['test_outside'].get('rmse'))} | {_f(d['slope_outside'], 2)} | {_f(d['test']['r2'])} | "
                     f"{_f(PAPER.get(k, {}).get('rmse'))} |")
        L.append("")

    L += ["## Selected hyperparameters", "", "| Experiment | best | OOF RMSE | seconds |", "|---|---|---|---|"]
    for k, d in R.items():
        L.append(f"| `{k}` | `{json.dumps(d['best_params'])}` | {_f(d['oof']['rmse'])} | {d['seconds']:.0f} |")
    (out / "RESULTS.md").write_text("\n".join(L) + "\n")
    summary = {k: {x: v for x, v in d.items() if not x.startswith("_")} for k, d in R.items()}
    (out / "summary.json").write_text(json.dumps(summary, indent=1))
    print(f"wrote {out/'RESULTS.md'} ({len(R)} runs)")
